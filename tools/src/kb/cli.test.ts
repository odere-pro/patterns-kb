describe('main', () => {
  it('runs only as the entry point, writing to the process', async () => {
    const file = path.join(path.dirname(fileURLToPath(import.meta.url)), 'cli.ts');
    const url = pathToFileURL(file).href;
    main(url, ['node', '/elsewhere.js']);
    main(url, ['node']);
    const broken = makeSandbox();
    writeKbFixture(broken.dir);
    broken.write('docs/data/content-model.json', '{"kinds":[]}');
    const writes: string[] = [];
    const said = (): string => writes.join('');
    const out = vi.spyOn(process.stdout, 'write').mockImplementation((s) => {
      writes.push(String(s));
      return true;
    });
    const err = vi.spyOn(process.stderr, 'write').mockImplementation((s) => {
      writes.push(String(s));
      return true;
    });
    const before = process.exitCode;
    const env = process.env['KB_ROOT'];
    try {
      process.env['KB_ROOT'] = root;
      main(url, ['node', file, 'validate', 'breaker']);
      await vi.waitFor(() => expect(said()).toContain('OK — 1 page(s)'));
      await vi.waitFor(() => expect(process.exitCode).toBe(0));
      main(url, ['node', file, 'get', 'break']);
      await vi.waitFor(() => expect(said()).toContain('unknown id: break\n'));
      await vi.waitFor(() => expect(process.exitCode).toBe(1));
      process.env['KB_ROOT'] = broken.dir;
      main(url, ['node', file, 'ls']);
      await vi.waitFor(() => expect(said()).toMatch(/kb\.mjs: .+/));
      await vi.waitFor(() => expect(process.exitCode).toBe(2));
    } finally {
      if (env === undefined) delete process.env['KB_ROOT'];
      else process.env['KB_ROOT'] = env;
      out.mockRestore();
      err.mockRestore();
      process.exitCode = before;
      broken.cleanup();
    }
  });

  it('stops quietly when the reader goes away, and throws any other stream error', () => {
    const stream = new PassThrough();
    quietOnClose(stream);
    const fail = (code: string): Error => Object.assign(new Error(code), { code });
    expect(() => stream.emit('error', fail('EPIPE'))).not.toThrow();
    expect(() => stream.emit('error', fail('EIO'))).toThrow('EIO');
  });

  it('shares one corpus across runs', async () => {
    const corpus = new Corpus(root);
    expect((await kb(corpus, 'get', 'retry', '--block', 'description')).out).toContain('Try again after a pause');
    expect((await kb(corpus, 'get', 'retry', '--block', 'description')).out).toContain('Try again after a pause');
  });
});

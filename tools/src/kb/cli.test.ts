  it('finds the page by --file, from its markdown', async () => {
    const md = path.join(root, 'docs/hazards/storm.md');
    expect(JSON.parse((await kb(root, 'refs', '--file', md, '--json')).out)['id']).toBe('storm');
  });

  it('refuses a --file that is missing, outside docs/, or no page', async () => {
    expect((await kb(root, 'refs', '--file', path.join(root, 'docs/nope.md'))).err).toBe(`no such file: ${path.join(root, 'docs/nope.md')}`);
    sb.write('elsewhere.md', 'x');
    expect((await kb(root, 'refs', '--file', path.join(root, 'elsewhere.md'))).err).toBe(`not under docs/: ${path.join(root, 'elsewhere.md')}`);
    sb.write('docs/reference/unlisted.md', '# Unlisted\n');
    expect((await kb(root, 'refs', '--file', path.join(root, 'docs/reference/unlisted.md'))).err).toBe(
      'docs/reference/unlisted.md: no row in docs/data/site-structure.json lists this page',
    );
    sb.write('site/index.html', '<html></html>');
    expect((await kb(root, 'refs', '--file', path.join(root, 'site/index.html'))).err).toBe(`not under docs/: ${path.join(root, 'site/index.html')}`);
  });

  it('says a page the structure file lists in an area of no kind is not a knowledge-base page', async () => {
    const why = (rel: string): string =>
      `${rel}: the structure file lists it in area "reference", which holds no knowledge-base kind — kb.mjs reads the seven kinds only`;
    for (const cmd of ['validate', 'refs']) {
      expect(await kb(root, cmd, '--file', path.join(root, 'docs/reference/notes.md')), cmd).toEqual({ code: 1, out: '', err: why('docs/reference/notes.md') });
    }
    // The kind pages still answer, and the listing leaves the reference row out.
    expect((await kb(root, 'ls')).out.endsWith('\n10 entries.')).toBe(true);
  });

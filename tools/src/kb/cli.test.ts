interface Ran {
  readonly code: number;
  readonly out: string;
  readonly err: string;
}

async function kb(at: string | Corpus, ...argv: string[]): Promise<Ran> {
  const out: string[] = [];
  const err: string[] = [];
  const code = await run(argv, { out: (l) => out.push(l), err: (l) => err.push(l) }, at);
  return { code, out: out.join('\n'), err: err.join('\n') };
}
const json = async (...argv: string[]): Promise<Record<string, unknown>> => {
  const r = await kb(root, ...argv, '--json');
  expect(r.code, r.err).toBe(0);
  return JSON.parse(r.out) as Record<string, unknown>;
};


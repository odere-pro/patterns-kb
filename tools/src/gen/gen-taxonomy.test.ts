/**
 * A clean tree the three data gates and the generator all pass on. The
 * reference page is a page under docs/ too, so its own tags are terms here.
 */
const CLEAN = {
  ...LIST,
  terms: [
    ...LIST.terms.slice(0, 2),
    { id: 'testing', facet: 'topic', label: 'Testing', definition: 'Proving it works.', applies: ['page'], owner: 'Tests' },
    LIST.terms[2],
    { id: 'validation', facet: 'skill', definition: 'Refusing bad input.', applies: ['page'], owner: 'Tests' },
    { ...LIST.terms[3], applies: ['page', 'exercise'] },
  ],
};

function cleanTree(): void {
  sb.write(TAG_LIST, `${JSON.stringify(CLEAN, null, 2)}\n`);
  sb.write(TYPES_FILE, `export const AREAS = ['caching'] as const;\nexport const TAGS = ['caching', 'resilience', 'testing', 'latency', 'validation', 'cloud'] as const;\n`);
  sb.write(ALLOWLIST, `${JSON.stringify({ ...HEADER, entries: [] }, null, 2)}\n`);
  sb.write(
    STRUCTURE,
    `${JSON.stringify(
      {
        ...HEADER,
        areas: [
          {
            id: 'caching',
            label: 'Caching',
            hub: { description: 'd', intro: 'i', tags: ['caching', 'latency'] },
            pages: [
              { slug: 'one', label: 'One', source: 'docs/caching/one.md' },
              { slug: 'two', label: 'Two', source: 'docs/caching/two.md' },
            ],
          },
        ],
      },
      null,
      2,
    )}\n`,
  );
  const page = (title: string, tags: string): string =>
    `---\ntitle: ${title}\ndescription: A page.\narea: caching\nowner: Tests\ntags: [${tags}]\nstatus: stable\n---\n\n# ${title}\n`;
  sb.write('docs/caching/one.md', page('One', 'caching, latency'));
  sb.write('docs/caching/two.md', page('Two', 'resilience, latency, cloud'));
  sb.write('docs/caching/three.md', page('Three', 'caching, cloud'));
}

/**
 * Registry rows data-O2 does not run in its sandbox, and why. Every other row
 * whose scans reach the edited file runs, so a new gate that reads the tag
 * list joins the scenario the day it is registered.
 *   - a row with no `scans` (context-layers, claims): it runs on every change
 *     because it holds the harness files — the context layers, the command
 *     claims — and reads no fact from a data file; data-O1 runs it on the real
 *     tree, which has the layers a sandbox would have to fake;
 *   - the suites and the type check (check-suite, check-bash-suite,
 *     check-types): they read no fact, and the vitest suite would run this
 *     file again;
 *   - a row with a `local_target` (the site gates): it reads a built
 *     site, which `make site-build` makes and neither a sandbox nor the
 *     checkout holds; the site job runs them after its build.
 */
const NOT_IN_SANDBOX = /check-(suite|bash-suite|types)\.ts$/;

describe('data-O2', () => {
  it('one fact edited in a clean tree changes only its data file and its rendered page, every gate reading it exiting 0', async () => {
    cleanTree();
    expectPass(await sb.run(spec));
    sb.commit('a clean tree');

    // Every gate that reads the edited file: each registry row whose scans reach it.
    const registry = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'docs/data/gates.json'), 'utf8')) as {
      gates: { id: string; local_command?: string; local_target?: string; scans?: string[] }[];
    };
    const gates: [string, GateSpec, string[]][] = [];
    for (const g of registry.gates) {
      if (g.scans === undefined || !matches(TAG_LIST, g.scans) || g.local_target !== undefined) continue;
      const [, program, ...argv] = (g.local_command ?? '').split(/\s+/);
      if (program === undefined || NOT_IN_SANDBOX.test(program)) continue;
      const mod = (await import(pathToFileURL(path.join(REPO_ROOT, program)).href)) as { spec: GateSpec };
      gates.push([g.id, mod.spec, argv]);
    }
    const ids = gates.map(([id]) => id);
    for (const id of ['json-sanity', 'site-structure', 'tags', 'tags-fresh']) expect(ids).toContain(id);
    // The imported specs are the ones this file tests directly.
    expect(gates.find(([id]) => id === 'tags')?.[1]).toBe(tagsSpec);
    expect(gates.find(([id]) => id === 'site-structure')?.[1]).toBe(structureSpec);
    expect(gates.find(([id]) => id === 'json-sanity')?.[1]).toBe(jsonSpec);
    const runAll = async (): Promise<void> => {
      for (const [id, g, argv] of gates) {
        const r = await sb.run(g, argv);
        expect(r.status, `${id}: ${r.output}`).toBe(0);
      }
    };
    await runAll();

    const data = JSON.parse(sb.read(TAG_LIST)) as { terms: Json[] };
    (data.terms[3] as Json)['definition'] = 'How long one call takes, as the caller feels it.';
    sb.write(TAG_LIST, `${JSON.stringify(data, null, 2)}\n`);
    expectPass(await sb.run(spec));
    await runAll();

    const changed = sb.git('status', '--porcelain').stdout.split('\n').filter((l) => l !== '').map((l) => l.slice(3));
    expect(changed.sort()).toEqual([OUT, TAG_LIST].sort());
    expect(sb.read(OUT)).toContain('| `latency` | How long one call takes, as the caller feels it. | pages |');
  });
});

describe('data-O1', () => {
  it('every data file parses and opens with its header; every gate reading one and every freshness check exits 0; each reference page opens with its stamp', async () => {
    const tracked = (patterns: string[]): string[] =>
      fs.readdirSync(path.join(REPO_ROOT, 'docs/data'), { recursive: true, withFileTypes: false })
        .map((f) => `docs/data/${String(f)}`)
        .filter((f) => matches(f, patterns));
    const dataFiles = tracked(['docs/data/**/*.json', 'docs/data/*.json']);
    expect(dataFiles.length).toBeGreaterThan(0);
    for (const f of dataFiles) {
      const data = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, f), 'utf8')) as Json;
      expect(Object.keys(data).slice(0, 3), f).toEqual(['version', 'updated', 'note']);
    }

    // The gates reading a data file: every registry row whose scans reach one.
    // Not run here: the two suite runners and the type check, which read no data
    // file (and the suites would run this one again). Nor a row with a
    // local_target: the site gates read a built site (NOT_IN_SANDBOX).
    const registry = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'docs/data/gates.json'), 'utf8')) as {
      gates: { id: string; local_command?: string; local_target?: string; scans?: string[] }[];
    };
    const readers = registry.gates.filter(
      (g) => g.local_target === undefined && (g.scans === undefined || dataFiles.some((f) => matches(f, g.scans ?? []))),
    );
    const ran: string[] = [];
    for (const g of readers) {
      const [, program, ...argv] = (g.local_command ?? '').split(/\s+/);
      if (program === undefined || NOT_IN_SANDBOX.test(program)) continue;
      const mod = (await import(pathToFileURL(path.join(REPO_ROOT, program)).href)) as { spec: GateSpec };
      const r = await capture(mod.spec, argv, REPO_ROOT);
      expect(r.status, `${g.id}: ${r.output}`).toBe(0);
      ran.push(g.id);
    }
    for (const id of ['json-sanity', 'site-structure', 'tags', 'tags-fresh', 'gates-fresh', 'relations-fresh', 'tours-fresh']) expect(ran).toContain(id);

    // Each reference page a generator renders from a data file opens with its stamp.
    const stamped = fs
      .readdirSync(path.join(REPO_ROOT, 'docs/reference'))
      .filter((f) => f.endsWith('.md'))
      .map((f) => `docs/reference/${f}`)
      .filter((f) => /^source: docs\/data\//m.test(fs.readFileSync(path.join(REPO_ROOT, f), 'utf8')));
    expect(stamped).toContain(OUT);
    for (const f of stamped) {
      const text = fs.readFileSync(path.join(REPO_ROOT, f), 'utf8');
      const source = (/^source: (\S+)$/m.exec(text) as RegExpExecArray)[1] as string;
      const first = (text.split('\n---\n')[1] as string).trimStart().split('\n')[0] as string;
      const m = /^<!-- GENERATED by (\S+) from (\S+)\. Do not edit this file\. -->$/.exec(first);
      expect(m, `${f} opens with ${first}`).not.toBeNull();
      expect((m as RegExpExecArray)[2], f).toBe(source);
      expect(fs.existsSync(path.join(REPO_ROOT, (m as RegExpExecArray)[1] as string)), f).toBe(true);
    }
  }, 300_000);
});

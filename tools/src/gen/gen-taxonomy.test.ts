/**
 * The generated tag reference, and the data-file scenarios it is the model
 * case for (spec: kb.data, data-O1 and data-O2).
 *
 * The page is what an author reads before picking a tag, so the assertions on
 * it are about it saying the things that stop a wrong tag being written — the
 * inline form, the bounds the gate holds, the one topic, and which class may
 * use each term.
 */

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { spec as jsonSpec } from '../gates/check-json.js';
import { spec as structureSpec } from '../gates/check-site-structure.js';
import { ALLOWLIST, spec as tagsSpec } from '../gates/check-tags.js';
import type { GateSpec } from '../lib/gate.js';
import { fileStamp } from '../lib/generated.js';
import { matches } from '../lib/glob.js';
import { STRUCTURE, TYPES_FILE } from '../lib/published.js';
import { capture, expectFail, expectMisuse, expectPass, makeSandbox, REPO_ROOT, type Sandbox } from '../lib/sandbox.js';
import { COUNTS, TAG_LIST } from '../lib/tags.js';
import { classes, FIX, GENERATOR, NAME, OUT, render, spec } from './gen-taxonomy.js';

type Json = Record<string, unknown>;

const HEADER = { version: 1, updated: '2026-09-24', note: 'The tag list.' };
const LIST = {
  ...HEADER,
  facets: { topic: 'What is the page about?', skill: 'What does the reader do?', language: 'What machinery?' },
  terms: [
    { id: 'caching', facet: 'topic', label: 'Caching', definition: 'Keeping a copy | closer.', applies: ['page'], owner: 'Tests' },
    { id: 'resilience', facet: 'topic', label: 'Resilience', definition: 'Degrading gracefully.', applies: ['page', 'exercise'], owner: 'Tests' },
    { id: 'latency', facet: 'skill', definition: 'How long one call takes.', applies: ['page'], owner: 'Tests' },
    { id: 'cloud', facet: 'language', definition: 'Managed services.', applies: ['exercise'], owner: 'Tests' },
  ],
};

let sb: Sandbox;
beforeEach(() => {
  sb = makeSandbox();
  sb.write(TAG_LIST, `${JSON.stringify(LIST, null, 2)}\n`);
});
afterEach(() => sb.cleanup());

describe('render', () => {
  const page = render(LIST);

  it('carries frontmatter held to the rules it documents, and its source', () => {
    expect(page.startsWith('---\ntitle: Tags\n')).toBe(true);
    expect(page).toContain('tags: [testing, validation]');
    expect(page).toContain(`source: ${TAG_LIST}`);
  });

  it('opens its body with the stamp naming the generator and the tag list', () => {
    const body = page.split('\n---\n')[1] as string;
    expect(body.trimStart().split('\n')[0]).toBe(fileStamp(GENERATOR, TAG_LIST));
    expect(fileStamp(GENERATOR, TAG_LIST)).toBe(`<!-- GENERATED by ${GENERATOR} from ${TAG_LIST}. Do not edit this file. -->`);
  });

  it('shows the inline form, and states the bounds the gate holds', () => {
    expect(page).toContain('tags: [resilience, isolation, latency]');
    expect(page).toContain('block list');
    expect(page).toContain(`**${String(COUNTS.page.min)}-${String(COUNTS.page.max)} tags** and exactly **one topic**`);
    expect(page).toContain(`An exercise carries ${String(COUNTS.exercise.min)}-${String(COUNTS.exercise.max)} tags`);
  });

  it('lists each term once, one table per facet in facet order, a topic with its heading', () => {
    expect(page).toContain('One closed list of 4 tags for every page in this knowledge base: 2 topics, 1 skills and 1 languages.');
    const at = (s: string): number => page.indexOf(s);
    expect(at('## Topics')).toBeLessThan(at('## Skills'));
    expect(at('## Skills')).toBeLessThan(at('## Languages'));
    expect(page).toContain('| `caching` | Caching | Keeping a copy \\| closer. | pages |');
    expect(page).toContain('| `resilience` | Resilience | Degrading gracefully. | pages and exercises |');
    expect(page).toContain('| `latency` | How long one call takes. | pages |');
    expect(page).toContain('| `cloud` | Managed services. | exercises |');
    for (const id of ['caching', 'resilience', 'latency', 'cloud']) expect(page.split(`| \`${id}\` |`)).toHaveLength(2);
  });

  it('leaves a facet the list does not describe with an empty answer, never a crash', () => {
    const page2 = render({ ...LIST, facets: { topic: 'About.', skill: 'Doing.' } });
    expect(page2).toContain('| `language` |  |');
  });

  it('drops the table of a facet with no terms', () => {
    const page2 = render({ ...LIST, terms: LIST.terms.slice(0, 3) });
    expect(page2).not.toContain('## Languages');
    expect(page2).toContain('0 languages');
  });

  it('reads applies as words, and a term with none of the classes as nothing', () => {
    expect(classes(['page', 'exercise'])).toBe('pages and exercises');
    expect(classes(['exercise'])).toBe('exercises');
    expect(classes([])).toBe('nothing');
    expect(render({ ...LIST, terms: [{ ...LIST.terms[0], applies: 'page', label: 3 }] })).toContain('| `caching` |  | Keeping a copy \\| closer. | nothing |');
  });
});

describe('write and --check', () => {
  it('writes the page, then finds it in sync', async () => {
    const w = await sb.run(spec);
    expectPass(w);
    expect(w.out).toBe(`[${NAME}] wrote 1 of 1 file: ${OUT} (4 terms)`);
    expect(sb.read(OUT)).toBe(render(LIST));
    expect((await sb.run(spec)).out).toBe(`[${NAME}] wrote 0 of 1 file: ${OUT} (4 terms)`);
    const c = await sb.run(spec, ['--check']);
    expectPass(c);
    expect(c.out).toBe(`[${NAME}] ${OUT} is in sync with ${TAG_LIST} (4 terms)`);
  });

  it('reports a hand edit STALE with its repair command and changes no byte; the repair clears it', async () => {
    await sb.run(spec);
    sb.write(OUT, `${sb.read(OUT)}A line nobody generated.\n`);
    const before = sb.snapshot();
    const r = await sb.run(spec, ['--check']);
    expectFail(r, `[${NAME}] FAIL: ${OUT} is STALE — run: ${FIX}`);
    expect(sb.snapshot()).toEqual(before);
    await sb.run(spec);
    expectPass(await sb.run(spec, ['--check']));
  });

  it('rewrites the page after a tag-list edit, without a flag', async () => {
    await sb.run(spec);
    const edited = { ...LIST, terms: [...LIST.terms, { id: 'edge', facet: 'language', definition: 'Near the user.', applies: ['page'], owner: 'Tests' }] };
    sb.write(TAG_LIST, JSON.stringify(edited));
    expectFail(await sb.run(spec, ['--check']), 'is STALE');
    expect((await sb.run(spec)).out).toBe(`[${NAME}] wrote 1 of 1 file: ${OUT} (5 terms)`);
    expect(sb.read(OUT)).toContain('| `edge` | Near the user. | pages |');
  });

  it('leaves a page it did not write alone, and says so', async () => {
    sb.write(OUT, '# Tags\n\nWritten by hand.\n');
    const r = await sb.run(spec);
    expectPass(r);
    expect(r.out).toBe(`[${NAME}] left ${OUT} alone: it does not carry this generator's stamp`);
    expect(sb.read(OUT)).toBe('# Tags\n\nWritten by hand.\n');
    expectFail(await sb.run(spec, ['--check']), 'does not carry this generator\'s stamp');
  });

  it('fails a missing tag list and one that is no tag list, writing nothing', async () => {
    sb.rm(TAG_LIST);
    expectFail(await sb.run(spec), `[${NAME}] FAIL ${TAG_LIST}: is missing`);
    sb.write(TAG_LIST, '{"terms": []}');
    expectFail(await sb.run(spec), `${TAG_LIST}: is not a tag list`);
    sb.write(TAG_LIST, '{ nope');
    expectFail(await sb.run(spec), `${TAG_LIST}: is not a tag list`);
    expect(sb.exists(OUT)).toBe(false);
  });

  it('treats --fix and a stray argument as misuse', async () => {
    expectMisuse(await sb.run(spec, ['--fix']));
    expectMisuse(await sb.run(spec, [OUT]));
  });
});


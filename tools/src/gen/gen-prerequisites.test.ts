/**
 * The prerequisite graph and its reference page, built from the relations
 * file. What is defended: the records are exactly the relations file's
 * requires and symmetric edges, in reading order, each neighbour once; both
 * outputs are written and checked byte for byte; the file keeps its date
 * while nothing else changes and takes HEAD's when anything does; a hand
 * edit, or a changed title, is STALE with the one repair; nothing is written
 * from a source with findings; and on the real tree the committed outputs
 * are what the generator makes.
 */

import fs from 'node:fs';
import path from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { capture, expectFail, expectMisuse, expectPass, makeSandbox, REPO_ROOT, type Sandbox } from '../lib/sandbox.js';
import { STRUCTURE, structureRows, type PageRow } from '../lib/page-refs.js';
import {
  buildRecords,
  CONTENT_MODEL,
  FIX,
  NONE,
  noteOf,
  OUT,
  REFERENCE,
  relatedPairs,
  RELATIONS,
  renderReference,
  spec,
  type PrereqFile,
} from './gen-prerequisites.js';
import {
  EDGES,
  HEADER,
  headOf,
  json,
  LEARNING_VERBS,
  learningModelJson,
  learningPageText,
  PREREQ_RECORDS,
  record,
  rowOf,
  sourceTree,
  VERBS,
} from '../lib/fixtures.js';

let sb: Sandbox;
beforeEach(() => {
  sb = makeSandbox();
});
afterEach(() => sb.cleanup());

const SYMMETRIC = ['combines-with'];
const findings = (err: string): string[] => err.split('\n').filter((l) => l.startsWith('[prerequisites-fresh] FAIL'));

describe('the outputs', () => {
  it('writes the graph as the records of the requires and symmetric edges, in reading order, and the reference page', async () => {
    sourceTree(sb);
    let r = await sb.run(spec);
    expectPass(r);
    expect(r.out).toBe(`[prerequisites-fresh] wrote 2 of 2 outputs from ${RELATIONS} (4 records, 2 requires edges)`);
    expect(JSON.parse(sb.read(OUT))).toEqual({ ...HEADER, updated: headOf(sb), note: noteOf(SYMMETRIC), records: PREREQ_RECORDS });

    const page = sb.read(REFERENCE);
    expect(page).toContain(`<!-- GENERATED by tools/src/gen/gen-prerequisites.ts from ${RELATIONS}. Do not edit this file. -->`);
    expect(page.replace(/\n/g, ' ')).toContain(
      'There are 4 records: 2 of them name something to read first, through 2 requires edges, and 1 pair of pages is related both ways.',
    );
    expect(page).toContain('| [Alpha](../patterns/alpha.md) | What alpha is, in one line | [Beta](../patterns/beta.md) | [Gamma](../patterns/gamma.md) |');
    expect(page).toContain(`| [Delta](../hazards/delta.md) | What delta is, in one line | ${NONE} | ${NONE} |`);
    expect(page).toContain('\n## patterns\n');
    expect(page).toContain('\n## hazards\n');
    expect(page).not.toContain('## themes');

    r = await sb.run(spec, ['--check']);
    expectPass(r);
    expect(r.out).toBe(`[prerequisites-fresh] ${OUT} and ${REFERENCE} are in sync with ${RELATIONS} (4 records, 2 requires edges)`);

    // generation-O2 on this generator: a second run changes no byte.
    const once = sb.snapshot();
    r = await sb.run(spec);
    expect(r.out).toBe(`[prerequisites-fresh] wrote 0 of 2 outputs from ${RELATIONS} (4 records, 2 requires edges)`);
    expect(sb.snapshot()).toEqual(once);
  });

  it('reports each hand-edited output as STALE with the one repair, changing nothing; the repair clears both', async () => {
    sourceTree(sb);
    await sb.run(spec);
    sb.write(REFERENCE, `${sb.read(REFERENCE)}a line someone appended\n`);
    sb.write(OUT, sb.read(OUT).replace('"requires": ["beta"]', '"requires": []'));
    const before = sb.snapshot();
    const r = await sb.run(spec, ['--check']);
    expectFail(r);
    expect(r.out).toBe('');
    expect(r.err.split('\n').filter((l) => l.includes(' is STALE — run: '))).toEqual([
      `[prerequisites-fresh] FAIL: ${OUT} is STALE — run: ${FIX}`,
      `[prerequisites-fresh] FAIL: ${REFERENCE} is STALE — run: ${FIX}`,
    ]);
    expect(sb.snapshot()).toEqual(before);
    expectPass(await sb.run(spec));
    expectPass(await sb.run(spec, ['--check']));
  });

  it('a changed title is a changed label: --check prints the STALE line and exits 1', async () => {
    sourceTree(sb);
    await sb.run(spec);
    sb.write(rowOf('beta').source, learningPageText('beta').replace('title: Beta', 'title: Beta, renamed'));
    const r = await sb.run(spec, ['--check']);
    expectFail(r, `[prerequisites-fresh] FAIL: ${OUT} is STALE — run: ${FIX}`);
    expect(r.err).toContain(`[prerequisites-fresh] FAIL: ${REFERENCE} is STALE — run: ${FIX}`);
  });

  it('never overwrites a graph file it did not write', async () => {
    sourceTree(sb);
    sb.write(OUT, json({ ...HEADER, records: [] }));
    const r = await sb.run(spec);
    expectPass(r);
    expect(r.err).toBe(`[prerequisites-fresh] skipped ${OUT}: it does not carry this generator's stamp, so it is not ours to write`);
    expect(JSON.parse(sb.read(OUT))).toEqual({ ...HEADER, records: [] });
  });

  it('keeps its date while nothing else in it changes, and takes HEAD’s when a page description does', async () => {
    sourceTree(sb);
    await sb.run(spec);
    const dated = (): string => (JSON.parse(sb.read(OUT)) as { updated: string }).updated;
    expect(dated()).toBe(headOf(sb));

    // An older date, every other byte the same: the file keeps it, and --check agrees.
    sb.write(OUT, sb.read(OUT).replace(`"updated": "${headOf(sb)}"`, '"updated": "2026-01-02"'));
    let r = await sb.run(spec);
    expect(r.out).toContain('wrote 0 of 2 outputs');
    expect(dated()).toBe('2026-01-02');
    expectPass(await sb.run(spec, ['--check']));

    // No data source moves, only a page's description: the content changed, so the date does.
    sb.write(rowOf('delta').source, learningPageText('delta').replace('description: What delta is', 'description: What delta really is'));
    r = await sb.run(spec, ['--check']);
    expectFail(r, `[prerequisites-fresh] FAIL: ${OUT} is STALE — run: ${FIX}`);
    await sb.run(spec);
    expect(dated()).toBe(headOf(sb));
    expect(sb.read(OUT)).toContain('"definition": "What delta really is, in one line"');
  });

  it('names the missing commit, and writes nothing, when the content changed and HEAD has no date to give it', async () => {
    sourceTree(sb);
    sb.git('update-ref', '-d', 'HEAD');
    const r = await sb.run(spec);
    expectFail(r);
    expect(r.err).toBe(
      `[prerequisites-fresh] FAIL: cannot read the committer date of HEAD, which ${OUT} carries as \`updated\` when its content changes — commit first`,
    );
    expect(sb.exists(OUT)).toBe(false);
  });

  it('lists a pair joined by two symmetric verbs once on each side, where its first edge puts it', async () => {
    const confused = { id: 'often-confused-with', label: 'Often confused with', inverse: 'often-confused-with' };
    sourceTree(sb, [
      ...EDGES,
      { a: 'gamma', verb: 'often-confused-with', b: 'alpha', note_a: '', note_b: '' },
      { a: 'delta', verb: 'often-confused-with', b: 'alpha', note_a: '', note_b: '' },
    ]);
    sb.write(CONTENT_MODEL, learningModelJson([...LEARNING_VERBS, confused]));
    expectPass(await sb.run(spec));
    const graph = JSON.parse(sb.read(OUT)) as PrereqFile;
    expect(graph.records.map((r) => [r.id, r.related])).toEqual([
      ['alpha', ['gamma', 'delta']],
      ['beta', []],
      ['gamma', ['alpha']],
      ['delta', ['alpha']],
    ]);
    expect(sb.read(REFERENCE).replace(/\n/g, ' ')).toContain('and 2 pairs of pages are related both ways.');
  });

  it('exits 2 on misuse, writing nothing', async () => {
    sourceTree(sb);
    const before = sb.snapshot();
    expectMisuse(await sb.run(spec, ['--nope']));
    expect(sb.snapshot()).toEqual(before);
  });
});

describe('a source with findings writes nothing', () => {
  it('names each missing data file, and one that is not an object', async () => {
    let r = await sb.run(spec);
    expect(findings(r.err)).toEqual([RELATIONS, CONTENT_MODEL, STRUCTURE].map((f) => `[prerequisites-fresh] FAIL ${f}: is missing — ${OUT} is built from it`));
    sourceTree(sb);
    sb.write(RELATIONS, '[]\n');
    r = await sb.run(spec);
    expect(findings(r.err)).toEqual([`[prerequisites-fresh] FAIL ${RELATIONS}: is not a JSON object`]);
    expect(sb.exists(OUT)).toBe(false);
  });

  it('names a verb table it cannot use, a model without the requires verb, a structure without areas, and a file without edges', async () => {
    sourceTree(sb);
    sb.write(CONTENT_MODEL, json({ ...HEADER, relations: { verbs: [] } }));
    sb.write(STRUCTURE, json({ ...HEADER }));
    sb.write(RELATIONS, json({ ...HEADER }));
    let r = await sb.run(spec);
    expect(findings(r.err)).toEqual([
      `[prerequisites-fresh] FAIL ${CONTENT_MODEL}: has no relations.verbs list`,
      `[prerequisites-fresh] FAIL ${STRUCTURE}: has no areas list, so no page is published`,
      `[prerequisites-fresh] FAIL ${RELATIONS}: has no relations list`,
    ]);

    sourceTree(sb);
    sb.write(CONTENT_MODEL, learningModelJson(VERBS));
    r = await sb.run(spec);
    expect(findings(r.err)).toEqual([`[prerequisites-fresh] FAIL ${CONTENT_MODEL}: has no "prerequisite" verb, the one a record's requires list is built from`]);
    expect(sb.exists(OUT)).toBe(false);
  });

  it('names an edge to a page that is not published, once per page, and ignores one of another verb', async () => {
    sourceTree(sb, [
      ...EDGES,
      { a: 'alpha', verb: 'prerequisite', b: 'ghost', note_a: '', note_b: '' },
      { a: 'ghost', verb: 'combines-with', b: 'beta', note_a: '', note_b: '' },
      { a: 'phantom', verb: 'variant-of', b: 'beta', note_a: '', note_b: '' },
      'not a record',
    ]);
    const r = await sb.run(spec);
    expect(findings(r.err)).toEqual([`[prerequisites-fresh] FAIL ${RELATIONS}: names ghost, which is no published page — run: make gate G=check-relations`]);
    expect(sb.exists(OUT)).toBe(false);
  });

  it('names a record page that is missing, or that declares no description', async () => {
    sourceTree(sb);
    sb.rm(rowOf('delta').source);
    sb.write(rowOf('gamma').source, learningPageText('gamma').replace(/^description: .*\n/m, ''));
    const r = await sb.run(spec);
    expect(findings(r.err)).toEqual([
      `[prerequisites-fresh] FAIL ${rowOf('gamma').source}: declares no description — its prerequisite record reads it from the page (or the page is missing)`,
      `[prerequisites-fresh] FAIL ${rowOf('delta').source}: declares no title — its prerequisite record reads it from the page (or the page is missing)`,
      `[prerequisites-fresh] FAIL ${rowOf('delta').source}: declares no description — its prerequisite record reads it from the page (or the page is missing)`,
    ]);
    expect(sb.exists(OUT)).toBe(false);
  });
});

describe('the helpers', () => {
  const rows: PageRow[] = [
    { slug: 'x', route: '/x.html', source: 'docs/a/x.md', area: 'a', top: 'a' },
    { slug: 'y', route: '/y.html', source: 'docs/a/y.md', area: 'a', top: 'a' },
    { slug: 'z', route: '/z.html', source: 'docs/b/z.md', area: 'b', top: 'b' },
  ];

  it('buildRecords gives a page that is only required a record of its own, and skips pages on no such edge', () => {
    const facts = new Map([['docs/a/y.md', { title: 'Y', description: 'Why' }]]);
    expect(buildRecords([{ a: 'x', verb: 'prerequisite', b: 'y' }], new Set(), rows, facts)).toEqual([
      { id: 'x', label: '', definition: '', route: '/x.html', requires: ['y'], related: [] },
      { id: 'y', label: 'Y', definition: 'Why', route: '/y.html', requires: [], related: [] },
    ]);
  });

  it('buildRecords lists each neighbour once, in the order of the edges that first name it', () => {
    const edges = [
      { a: 'x', verb: 'combines-with', b: 'z' },
      { a: 'y', verb: 'confused', b: 'x' },
      { a: 'z', verb: 'confused', b: 'x' },
      { a: 'x', verb: 'prerequisite', b: 'y' },
      { a: 'x', verb: 'prerequisite', b: 'y' },
    ];
    const got = buildRecords(edges, new Set(['combines-with', 'confused']), rows, new Map());
    expect(got.map((r) => [r.id, r.requires, r.related])).toEqual([
      ['x', ['y'], ['z', 'y']],
      ['y', [], ['x']],
      ['z', [], ['x']],
    ]);
    expect(relatedPairs(got)).toBe(2);
  });

  it('relatedPairs counts each unordered pair once, whichever side lists it', () => {
    expect(relatedPairs([record('a', [], ['b', 'c']), record('b', [], ['a']), record('c', [], ['a'])])).toBe(2);
    expect(relatedPairs([record('a', [], ['b'])])).toBe(1);
    expect(relatedPairs([])).toBe(0);
  });

  it('renderReference escapes a label that would break the table, and states a single edge and pair in the singular', () => {
    const file: PrereqFile = {
      ...HEADER,
      records: [
        { id: 'x', label: 'X | pipe', definition: 'Defines *x*', route: '/x.html', requires: ['z'], related: ['y'] },
        { id: 'y', label: 'Y', definition: 'Y.', route: '/y.html', requires: [], related: ['x'] },
        { id: 'z', label: 'Z', definition: 'Z.', route: '/z.html', requires: [], related: [] },
      ],
    };
    const page = renderReference(file, rows, new Map([['a', 'Area A'], ['b', 'Area B']]), ['combines-with', 'alternative-to']);
    expect(page).toContain('| [X \\| pipe](../a/x.md) | Defines \\*x\\* | [Z](../b/z.md) | [Y](../a/y.md) |');
    expect(page.replace(/\n/g, ' ')).toContain('through 1 requires edge, and 1 pair of pages is related');
    expect(page.replace(/\n/g, ' ')).toContain('`combines-with` and `alternative-to` edges');
    expect(page.indexOf('## Area A')).toBeLessThan(page.indexOf('## Area B'));
  });
});

describe('the real tree', () => {
  it('finds both committed outputs in sync, counting what a plain walk of the relations file counts', async () => {
    const rel = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, RELATIONS), 'utf8')) as { relations: { a: string; verb: string; b: string }[] };
    const symmetric = new Set(['combines-with', 'alternative-to', 'often-confused-with']);
    const ends = new Set(rel.relations.filter((e) => e.verb === 'prerequisite' || symmetric.has(e.verb)).flatMap((e) => [e.a, e.b]));
    const edges = rel.relations.filter((e) => e.verb === 'prerequisite').length;
    const r = await capture(spec, ['--check'], REPO_ROOT);
    expectPass(r);
    expect(r.out).toBe(`[prerequisites-fresh] ${OUT} and ${REFERENCE} are in sync with ${RELATIONS} (${ends.size} records, ${edges} requires edges)`);
    const structure = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, STRUCTURE), 'utf8')) as unknown;
    expect((structureRows(structure) as { rows: readonly unknown[] }).rows.length).toBeGreaterThan(ends.size);
  });
});

const REG = gatesRegistry((r) => {
  // Three divergences from the base, each one a case this file owns: a gate a
  // person runs, so `runs` has a value with no CI job behind it; a job that
  // only has an answer after the merge, which is both excluded from the
  // required checks and absent from an ordinary change; and a symptom, because
  // the triage table is rendered from them too.
  r.required_contexts.exclude['guard-main'] = 'it never reports on a pull request';
  r.conditional_jobs['guard-main'] = 'it only has an answer after the merge';
  r.gates.push(HUMAN_GATE, AFTER_MERGE_GATE);
  r.symptoms.push({ name: 'A flake', anchor: 'a-flake', where: '—' });
});

const GUIDE = 'docs/guide.md';
const guidePage = [
  '# A guide',
  '',
  'Prose that must survive every regeneration.',
  '',
  '<!-- gate-count:start -->',
  'a stale line',
  '<!-- gate-count:end -->',
  '',
  'More prose.',
  '',
].join('\n');

let sb: Sandbox;
beforeEach(() => {
  sb = makeSandbox();
  sb.write(SRC, `${JSON.stringify(REG, null, 2)}\n`);
  sb.write(TRIAGE, triagePage(['Widget check', 'Someone reads it', 'A flake']));
});
afterEach(() => sb.cleanup());

/** The text between one block's markers, markers excluded. */
const inside = (text: string, name: string): string => {
  const [open, close] = markers(name);
  return text.slice(text.indexOf(open) + open.length, text.indexOf(close));
};

describe('rendering', () => {
  it('lists a human-only gate in the reference but never in the symptom table', () => {
    expect(renderReference(REG)).toContain('Someone reads it');
    const table = renderSymptomTable(REG).join('\n');
    expect(table).toContain('Widget check');
    // A judgement a person makes cannot be why a build went red, so it has no
    // row in a symptom table — the distinction the two renderings keep.
    expect(table).not.toContain('Someone reads it');
  });

  it('wraps the whole table, header row included, under a table stamp', () => {
    const table = renderSymptomTable(REG);
    expect(table[0]).toBe(`<!-- GENERATED by ${GENERATOR} from ${SRC}. Do not edit this table. -->`);
    expect(table[2]).toBe('| Failing step | Job | Reproduce it alone |');
    expect(table).toContain('| [Widget check](#widget-check) | `validate` | `make gate G=check-widget` |');
  });

  it('keeps the symptom rows that are not gates, after the gates', () => {
    const table = renderSymptomTable(REG);
    expect(table.at(-1)).toBe('| [A flake](#a-flake) | — | — |');
  });

  it('escapes a pipe inside a cell', () => {
    // write-or-check-C8.
    expect(cell('a | b')).toBe('a \\| b');
    const piped = gatesRegistry((r) => {
      (r.gates[0] as { protects: string }).protects = 'either | or';
    });
    expect(renderReference(piped)).toContain('either \\| or');
  });

  it('leaves a row unlinked when its runbook has no anchor', () => {
    const bare = gatesRegistry((r) => {
      r.gates[0] = { ...omit(WIDGET_GATE, 'ci_job'), runbook: 'docs/reference/triage.md' };
    });
    expect(renderSymptomTable(bare).join('\n')).toContain('| Widget check | `?` |');
  });

  it('splits a runbook into its file and its anchor, and links it from anywhere', () => {
    expect(fileOf('docs/reference/triage.md#x')).toBe('docs/reference/triage.md');
    expect(anchorOf('docs/reference/triage.md#x')).toBe('x');
    expect(anchorOf('docs/reference/triage.md')).toBeNull();
    expect(hrefFrom('docs/reference', 'docs/reference/triage.md#x')).toBe('triage.md#x');
    expect(hrefFrom('docs/reference', 'docs/data/gates.json')).toBe('../data/gates.json');
  });

  it('labels a run place by its workflow file, `make`, a person, or its own id', () => {
    expect(placeLabel(REG, 'ci')).toBe('`validate.yml`');
    expect(placeLabel(REG, 'local')).toBe('`make`');
    expect(placeLabel(REG, 'human')).toBe('a person');
    expect(placeLabel(REG, 'on-a-tuesday')).toBe('`on-a-tuesday`');
  });

  it('says out loud when nothing compares a gate to what runs', () => {
    const noted = gatesRegistry((r) => {
      r.gates[0] = { ...omit(WIDGET_GATE, 'wired'), wired_note: 'two different shells' };
    });
    expect(renderReference(noted)).toContain('**Not compared automatically:** two different shells');
  });

  it('opens the reference with frontmatter naming its source, then the stamp', () => {
    const page = renderReference(REG);
    const lines = page.split('\n');
    const close = lines.indexOf('---', 1);
    expect(lines.slice(1, close)).toContain(`source: ${SRC}`);
    // output-ownership-C1: the stamp is the first body line.
    expect(lines.slice(close + 1).find((l) => l !== '')).toBe(
      `<!-- GENERATED by ${GENERATOR} from ${SRC}. Do not edit this file. -->`,
    );
    // write-or-check-C7: one trailing newline, never two.
    expect(page.endsWith('\n')).toBe(true);
    expect(page.endsWith('\n\n')).toBe(false);
  });

  it('names the gates only CI runs, and the ones only make runs', () => {
    const page = renderReference(REG).replace(/\s+/g, ' ');
    expect(page).toContain('One gate runs only in CI, never from `make`: **Main push guard**.');
    const localOnly = gatesRegistry((r) => {
      r.gates.push({ ...WIDGET_GATE, id: 'local-a', name: 'Local A', runs: ['local'] });
      r.gates.push({ ...WIDGET_GATE, id: 'local-b', name: 'Local B', runs: ['local'] });
    });
    expect(renderReference(localOnly).replace(/\s+/g, ' ')).toContain(
      '2 gates have no step in CI, so a green change says nothing about them: **Local A** and **Local B**.',
    );
    expect(renderReference(gatesRegistry()).replace(/\s+/g, ' ')).toContain(
      'Every gate CI runs also runs from `make`',
    );
  });

  it('agrees with itself in the singular and the plural on both sides of the CI/make split', () => {
    const ciOnlyTwo = gatesRegistry((r) => {
      r.gates.push({ ...AFTER_MERGE_GATE, id: 'ci-a', name: 'CI A', runs: ['ci'] });
      r.gates.push({ ...AFTER_MERGE_GATE, id: 'ci-b', name: 'CI B', runs: ['ci'] });
    });
    expect(renderReference(ciOnlyTwo).replace(/\s+/g, ' ')).toContain(
      '2 gates run only in CI, never from `make`: **CI A** and **CI B**.',
    );
    const localOnlyOne = gatesRegistry((r) => {
      r.gates.push({ ...WIDGET_GATE, id: 'local-a', name: 'Local A', runs: ['local'] });
    });
    expect(renderReference(localOnlyOne).replace(/\s+/g, ' ')).toContain(
      'One gate has no step in CI, so a green change says nothing about it: **Local A**.',
    );
  });

  it('drops the workflow clause when the change place names no workflow file', () => {
    const noWorkflow = gatesRegistry((r) => {
      r.runs_values['ci'] = { meaning: 'a validate.yml step' };
    });
    expect(renderReference(noWorkflow).replace(/\s+/g, ' ')).toContain(
      "A protected branch requires the change workflow's gate-holding jobs — the job names are the check names:",
    );
  });

  it('falls back to a placeholder example when no gate is a `make gate G=` program', () => {
    const noExample = gatesRegistry((r) => {
      r.gates[0] = { ...WIDGET_GATE, command: 'node scripts/check.mjs' };
    });
    expect(renderReference(noExample)).toContain('make gate G=<program>');
  });

  it('skips a change-place gate with no job when counting jobs a change reddens or waits on', () => {
    // changeGates/afterMergeGates fold a missing ci_job to '' before the
    // membership test, the same defensive shape ciJobs uses.
    const noJob = gatesRegistry((r) => {
      r.gates.push(omit({ ...WIDGET_GATE, id: 'unwired-check' }, 'ci_job'));
    });
    const prose = renderGateCount(noJob).join(' ').replace(/\s+/g, ' ');
    expect(prose).toContain('2 on every change in CI');
  });

  it('renders a fix that is a command as code, and prose as prose', () => {
    const fixed = gatesRegistry((r) => {
      (r.gates[0] as { fix: string }).fix = FIX;
    });
    expect(renderReference(fixed)).toContain('- **Fix:** `make gates`');
    expect(renderReference(gatesRegistry())).toContain('- **Fix:** Reshape the widget.');
  });

  it('offers make fix only when a row declares a repair, and says why not otherwise', () => {
    expect(renderReference(REG).replace(/\s+/g, ' ')).toContain(
      'No gate declares a repair yet, so `make fix` has nothing to run and exits 2',
    );
    const fixable = gatesRegistry((r) => {
      (r.gates[0] as { fixable: boolean }).fixable = true;
    });
    const page = renderReference(fixable);
    expect(page.replace(/\s+/g, ' ')).toContain('The deterministic repairs, applied rather than reported — **Widget check**:');
    expect(page).toContain('```bash\nmake fix\n```');
  });

  it('says a gate needs nothing when it declares no tool', () => {
    const bare = gatesRegistry((r) => {
      r.gates[0] = omit(WIDGET_GATE, 'requires');
    });
    expect(renderReference(bare)).toContain('- **Needs:** nothing you do not already have');
  });
});

describe('the required-check list and the counts, derived rather than remembered', () => {
  it('takes the distinct CI jobs in registry order, minus the excluded', () => {
    expect(ciJobs(REG)).toEqual(['validate', 'guard-main']);
    expect(requiredContexts(REG)).toEqual(['validate']);
    const page = renderReference(REG).replace(/\s+/g, ' ');
    expect(page).toContain('- `validate`');
    expect(page).toContain('`guard-main` is deliberately not required: it never reports on a pull request.');
  });

  it('skips a change-place gate that names no job, rather than listing "undefined"', () => {
    // The registry's own contract ("every gate that runs on a change has
    // one") makes this a malformed entry, not an ordinary shape — but the
    // field is optional in the type, and a hand-edited registry.json is not
    // re-checked by the compiler.
    const noJob = gatesRegistry((r) => {
      r.gates.push(omit({ ...WIDGET_GATE, id: 'unwired-check' }, 'ci_job'));
    });
    expect(ciJobs(noJob)).toEqual(['validate']);
  });

  it('treats an absent conditional_jobs map the same as an empty one', () => {
    // The field is optional on `Registry` — most of this suite's fixtures set
    // it to `{}` explicitly, which is a different value than JavaScript ever
    // sees from a registry.json that omits the key entirely.
    const noMap = omit(gatesRegistry(), 'conditional_jobs');
    expect(conditionalJobs(noMap)).toEqual([]);
  });

  it('says none are required when no job is left to require', () => {
    const none = gatesRegistry((r) => {
      r.required_contexts.exclude['validate'] = 'a fixture';
    });
    expect(renderReference(none)).toContain('- none');
  });

  it('counts the gates by where they run, and says so when a person is one of them', () => {
    const prose = renderGateCount(REG).join(' ').replace(/\s+/g, ' ');
    expect(prose).toContain('**3 check gates** guard this repo');
    expect(prose).toContain('1 run from `make` on your own machine');
    expect(prose).toContain('1 on every change in CI');
    expect(prose).toContain('1 more only after a merge');
    expect(prose).toContain("1 is not code but a person's judgement");
  });

  it('pluralises the person-judgement clause when more than one gate is one', () => {
    const twoJudged = gatesRegistry((r) => {
      r.gates.push(HUMAN_GATE, { ...HUMAN_GATE, id: 'reads-it-too' });
    });
    const prose = renderGateCount(twoJudged).join(' ').replace(/\s+/g, ' ');
    expect(prose).toContain("2 are not code but a person's judgement");
  });

  it('agrees with itself in the singular, and holds no relative link', () => {
    const one = renderGateCount(gatesRegistry()).join(' ').replace(/\s+/g, ' ');
    expect(one).toContain('**1 check gate** guard this repo: 1 run from `make` on your own machine and 1 on every change in CI.');
    // marked-blocks-C9: the block lands in files at different depths.
    expect(one).not.toMatch(/\]\((?!https?:)/);
  });

  it('joins a list the way English does, and wraps prose greedily', () => {
    expect(englishList([])).toBe('nothing');
    expect(englishList(['a'])).toBe('a');
    expect(englishList(['a', 'b'])).toBe('a and b');
    expect(englishList(['a', 'b', 'c'])).toBe('a, b and c');
    expect(wrap('one two three four', 9)).toEqual(['one two', 'three', 'four']);
    expect(wrap('supercalifragilistic x', 5)).toEqual(['supercalifragilistic', 'x']);
    expect(wrap('')).toEqual([]);
    expect(wrap('   ')).toEqual([]);
    // Edge whitespace splits into an empty word, which must not reach a line.
    expect(wrap('a ')).toEqual(['a']);
    expect(wrap(' a')).toEqual(['a']);
  });
});

describe('the generator', () => {
  it('writes every output, and a second run changes nothing', async () => {
    const first = await sb.run(spec);
    expectPass(first);
    expect(first.out).toBe(`[gates-fresh] wrote 2 of 2 outputs from ${SRC} (3 gates)`);
    const triage = sb.read(TRIAGE);
    expect(triage).toContain('Hand-written prose that must survive');
    const snapshot = sb.snapshot();

    expectPass(await sb.run(spec));
    expect(sb.snapshot()).toEqual(snapshot);
    const check = await sb.run(spec, ['--check']);
    expectPass(check);
    expect(check.out).toBe(`[gates-fresh] ${REFERENCE} and ${TRIAGE} are in sync with ${SRC}`);
  });

  it('--check fails when the reference is hand-edited, and names the one repair', async () => {
    await sb.run(spec);
    sb.write(REFERENCE, `${sb.read(REFERENCE)}someone typed here\n`);
    const r = await sb.run(spec, ['--check']);
    expectFail(r, `${REFERENCE} is STALE — run: ${FIX}`);
  });

  it('--check fails when the symptom table is hand-edited', async () => {
    await sb.run(spec);
    sb.write(TRIAGE, sb.read(TRIAGE).replace('[Widget check](#widget-check)', '[Widgit check](#widget-check)'));
    expectFail(await sb.run(spec, ['--check']), `${TRIAGE} is STALE`);
  });

  it('says which marker is missing rather than writing half a page', async () => {
    const broken = triagePage().replace('<!-- gates-symptoms:end -->\n', '');
    sb.write(TRIAGE, broken);
    const r = await sb.run(spec);
    expectFail(r, `[gates-fresh] FAIL ${TRIAGE}: lacks the <!-- gates-symptoms:end --> marker`);
    expect(sb.read(TRIAGE)).toBe(broken);
  });

  it('says the triage page is missing rather than creating one', async () => {
    sb.rm(TRIAGE);
    const r = await sb.run(spec);
    expectFail(r, `[gates-fresh] FAIL ${TRIAGE}: is missing`);
    expect(sb.exists(TRIAGE)).toBe(false);
  });

  it('never writes over a hand-written page at the reference path', async () => {
    sb.write(REFERENCE, '# Somebody wrote this\n');
    const r = await sb.run(spec);
    expectPass(r);
    expect(r.err).toContain(`skipped ${REFERENCE}`);
    expect(sb.read(REFERENCE)).toBe('# Somebody wrote this\n');
  });

  it('says the registry is missing, or not JSON, rather than writing an empty reference', async () => {
    sb.rm(SRC);
    expectFail(await sb.run(spec), `[gates-fresh] FAIL ${SRC}: is missing`);
    expect(sb.exists(REFERENCE)).toBe(false);
    sb.write(SRC, 'not json');
    expectFail(await sb.run(spec, ['--check']), `[gates-fresh] FAIL ${SRC}: is not valid JSON`);
    expect(sb.exists(REFERENCE)).toBe(false);
  });

  it('refuses a misspelt or extra argument before writing anything', async () => {
    for (const argv of [['--chekc'], ['--check', 'extra'], ['--fix']]) {
      expectMisuse(await sb.run(spec, argv));
    }
    expect(sb.exists(REFERENCE)).toBe(false);
  });

  it('declares its counted block in the real triage page only, for now', () => {
    expect(COUNT_FILES).toEqual([TRIAGE]);
  });
});

describe('a counted block in several files', () => {
  const gen = specFor([TRIAGE, GUIDE]);

  it('writes the same block into every declared file', async () => {
    sb.write(GUIDE, guidePage);
    expectPass(await sb.run(gen));
    const blocks = [inside(sb.read(TRIAGE), COUNT_BLOCK), inside(sb.read(GUIDE), COUNT_BLOCK)];
    expect(blocks[1]).toBe(blocks[0]);
    expect(blocks[0]).toContain('**3 check gates**');
    expectPass(await sb.run(gen, ['--check']));
  });

  it('writes the others when one declared file lacks its markers, then fails', async () => {
    // marked-blocks-C6: one broken page must not take the rest down with it.
    sb.write(GUIDE, '# A guide\n\nno markers here\n');
    const r = await sb.run(gen);
    expectFail(r, `[gates-fresh] FAIL ${GUIDE}: lacks the <!-- gate-count:start --> marker`);
    expect(r.out).toBe('');
    expect(sb.read(GUIDE)).toBe('# A guide\n\nno markers here\n');
    expect(inside(sb.read(TRIAGE), COUNT_BLOCK)).toContain('**3 check gates**');
  });

  it('names a declared file that is missing, and creates nothing', async () => {
    const r = await sb.run(gen);
    expectFail(r, `[gates-fresh] FAIL ${GUIDE}: is missing`);
    expect(sb.exists(GUIDE)).toBe(false);
  });

  it('splices only the symptom table into the triage page when the count-file list omits it', async () => {
    // TRIAGE is always the first file the generator touches — the symptom
    // table has nowhere else to go — but a count-file list that leaves it
    // out still owes it nothing more than that.
    const bare = specFor([]);
    expectPass(await sb.run(bare));
    expect(inside(sb.read(TRIAGE), SYMPTOM_BLOCK)).toContain('A flake');
    expect(inside(sb.read(TRIAGE), COUNT_BLOCK)).toBe(inside(triagePage(['Widget check', 'Someone reads it', 'A flake']), COUNT_BLOCK));
  });
});

describe('oracle scenarios', () => {
  it('marked-blocks-O1: three records, a stale line between markers, prose kept, the paragraph states 3', async () => {
    sb.write(SRC, `${JSON.stringify(REG, null, 2)}\n`);
    expect(REG.gates).toHaveLength(3);
    sb.write(GUIDE, guidePage);
    const gen = specFor([TRIAGE, GUIDE]);
    const [open, close] = markers(COUNT_BLOCK);

    for (const argv of [[], ['--check']]) {
      expectPass(await sb.run(gen, argv));
      const page = sb.read(GUIDE);
      expect(page.slice(0, page.indexOf(open))).toBe(guidePage.slice(0, guidePage.indexOf(open)));
      expect(page.slice(page.indexOf(close))).toBe(guidePage.slice(guidePage.indexOf(close)));
      const firstInside = inside(page, COUNT_BLOCK)
        .split('\n')
        .find((l) => l.trim() !== '');
      expect(firstInside?.startsWith('<!-- GENERATED by')).toBe(true);
      expect(inside(page, COUNT_BLOCK)).toContain('**3 check gates**');
      expect(inside(page, COUNT_BLOCK)).not.toContain('a stale line');
    }
  });

  it('generation-O1: an appended page line and a changed block number are each STALE; the repair clears both', async () => {
    expectPass(await sb.run(spec));
    expectPass(await sb.run(spec, ['--check']));
    sb.write(REFERENCE, `${sb.read(REFERENCE)}a line someone appended\n`);
    sb.write(TRIAGE, sb.read(TRIAGE).replace('**3 check gates**', '**4 check gates**'));
    const before = sb.snapshot();

    const r = await sb.run(spec, ['--check']);
    expectFail(r);
    const stale = r.err.split('\n').filter((l) => l.includes(' is STALE — run: '));
    expect(stale).toEqual([
      `[gates-fresh] FAIL: ${REFERENCE} is STALE — run: ${FIX}`,
      `[gates-fresh] FAIL: ${TRIAGE} is STALE — run: ${FIX}`,
    ]);
    expect(sb.snapshot()).toEqual(before);

    expectPass(await sb.run(spec));
    expectPass(await sb.run(spec, ['--check']));
  });

  it('generation-O2: after a run, a second run changes no byte and the check exits 0', async () => {
    expectPass(await sb.run(spec));
    const once = sb.snapshot();
    expectPass(await sb.run(spec));
    expect(sb.snapshot()).toEqual(once);
    expectPass(await sb.run(spec, ['--check']));
  });

  it('generation-O3: three outputs of one data file, each hand-edited, each STALE with one repair', async () => {
    sb.write(GUIDE, guidePage);
    const gen = specFor([TRIAGE, GUIDE]);
    expectPass(await sb.run(gen));
    // One hand edit per output: inside the reference, inside each counted block.
    sb.write(REFERENCE, sb.read(REFERENCE).replace('# Check gates', '# Check gates, edited'));
    for (const f of [TRIAGE, GUIDE]) sb.write(f, sb.read(f).replace('**3 check gates**', '**three check gates**'));

    const r = await sb.run(gen, ['--check']);
    expectFail(r);
    const stale = r.err.split('\n').filter((l) => l.includes(' is STALE — run: '));
    expect(stale).toEqual([REFERENCE, TRIAGE, GUIDE].map((f) => `[gates-fresh] FAIL: ${f} is STALE — run: ${FIX}`));

    expectPass(await sb.run(gen));
    expectPass(await sb.run(gen, ['--check']));
  });
});

describe('the real tree', () => {
  it('finds every real output in sync with the real registry, and counts its rows', async () => {
    // testing-C4: the rows are recounted here from the registry's own JSON,
    // and held to the count the rendered block states.
    const real = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, SRC), 'utf8')) as { gates: unknown[] };
    sb.rm('docs');
    sb.copyRepo(SRC, REFERENCE, ...COUNT_FILES);

    const r = await sb.run(spec, ['--check']);
    expectPass(r);
    const block = inside(sb.read(TRIAGE), COUNT_BLOCK).replace(/\s+/g, ' ');
    expect(block).toContain(`**${real.gates.length} check gates**`);
    expect(sb.read(REFERENCE)).toContain(`There are ${real.gates.length} of`);
    expect(gatesRegistryJson()).toContain('"widget-check"');
    expect(SYMPTOM_BLOCK).toBe('gates-symptoms');
  });
});

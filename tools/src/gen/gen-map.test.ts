/**
 * The docs map's page table, rendered from the structure file into its marked
 * block in docs/README.md (spec: kb.content.docs-map, map-page;
 * kb.generation.marked-blocks): one row per area that lists pages, written or
 * checked byte for byte, and nothing outside the markers touched.
 */

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { structureJson } from '../lib/fixtures.js';
import { capture, expectFail, expectMisuse, expectPass, makeSandbox, REPO_ROOT, type Sandbox } from '../lib/sandbox.js';
import { FIX, MAP, renderMap, SRC, spec, trail, type Area } from './gen-map.js';

let sb: Sandbox;
beforeEach(() => {
  sb = makeSandbox();
});
afterEach(() => sb.cleanup());

/** A hand-written map with an empty block. */
const MAP_PAGE = ['# Docs map', '', 'Every page, one link away.', '', '<!-- docs-map:start -->', '', '<!-- docs-map:end -->', '', 'After the block.', ''].join('\n');

function tree(): void {
  sb.write(SRC, structureJson({ caching: ['docs/patterns/caching/alpha.md'], reference: ['docs/reference/guide.md'] }));
  sb.write(MAP, MAP_PAGE);
}

describe('renderMap', () => {
  const areas: Area[] = [
    { id: 'patterns', label: 'Patterns', hub: { description: 'Every pattern.' }, pages: [] },
    { id: 'gof', label: 'Objects & Classes', nestUnder: 'patterns', hub: { description: 'The book.' } },
    {
      id: 'gof-creational',
      label: 'Creational',
      nestUnder: 'gof',
      hub: { description: 'Making objects | carefully, with `new`.' },
      pages: [
        { label: 'Singleton', source: 'docs/patterns/gof/creational/singleton.md' },
        { label: 'A [bracketed] | piped name', source: 'docs/patterns/gof/creational/odd.md' },
        { source: 'docs/patterns/gof/creational/unlabelled.md' },
        { label: 'Hand-written', source: 'site/src/content/docs/index.mdx' },
        { label: 'No source' },
      ],
    },
    { id: 'orphan', nestUnder: 'nowhere', pages: [{ label: 'Lost', source: 'docs/lost.md' }] },
  ];

  it('writes one row per area that lists pages: its trail, its clause, then its pages in order', () => {
    expect(renderMap(areas)).toEqual([
      '<!-- GENERATED by tools/src/gen/gen-map.ts from docs/data/site-structure.json. Do not edit this table. -->',
      '| Area | Read it for | Pages |',
      '| --- | --- | --- |',
      '| Patterns › Objects & Classes › Creational | Making objects \\| carefully, with `new`. | [Singleton](patterns/gof/creational/singleton.md) · [A \\[bracketed\\] \\| piped name](patterns/gof/creational/odd.md) · [unlabelled](patterns/gof/creational/unlabelled.md) |',
      '| orphan |  | [Lost](lost.md) |',
    ]);
  });

  it('stops a trail at a parent it has already named', () => {
    const loop: Area[] = [
      { id: 'a', label: 'A', nestUnder: 'b' },
      { id: 'b', label: 'B', nestUnder: 'a' },
    ];
    const byId = new Map(loop.map((x) => [x.id, x]));
    expect(trail(loop[0] as Area, byId)).toBe('B › A');
  });
});

describe('gen-map', () => {
  it('writes the block, leaves every byte outside it, then --check agrees and a second write changes nothing', async () => {
    tree();
    const wrote = await sb.run(spec);
    expectPass(wrote);
    expect(wrote.out).toBe(`[map-fresh] wrote 1 of 1 map block in ${MAP} (2 areas from ${SRC})`);
    const text = sb.read(MAP);
    expect(text.startsWith('# Docs map\n\nEvery page, one link away.\n\n<!-- docs-map:start -->\n\n<!-- GENERATED by')).toBe(true);
    expect(text.endsWith('\n\n<!-- docs-map:end -->\n\nAfter the block.\n')).toBe(true);
    expect(text).toContain('| patterns › caching | fixture | [Alpha](patterns/caching/alpha.md) |');
    expect(text).toContain('| reference | fixture | [Alpha](reference/guide.md) |');

    const check = await sb.run(spec, ['--check']);
    expectPass(check);
    expect(check.out).toBe(`[map-fresh] ${MAP} is in sync with ${SRC}`);

    const again = await sb.run(spec);
    expect(again.out).toBe(`[map-fresh] wrote 0 of 1 map block in ${MAP} (2 areas from ${SRC})`);
    expect(sb.read(MAP)).toBe(text);
  });

  it('a hand edit inside the block is STALE, names the repair and stays; one outside is not drift', async () => {
    tree();
    await sb.run(spec);
    sb.write(MAP, sb.read(MAP).replace('After the block.', 'After the block, reworded.'));
    expectPass(await sb.run(spec, ['--check']));

    const edited = sb.read(MAP).replace('[Alpha](patterns/caching/alpha.md)', '[Alpha, by hand](patterns/caching/alpha.md)');
    sb.write(MAP, edited);
    const r = await sb.run(spec, ['--check']);
    expectFail(r, `${MAP} is STALE — run: ${FIX}`);
    expect(r.out).toBe('');
    expect(sb.read(MAP)).toBe(edited);
  });

  it('a page added to the structure file makes the block STALE until the repair', async () => {
    tree();
    await sb.run(spec);
    sb.write(SRC, structureJson({ caching: ['docs/patterns/caching/alpha.md', 'docs/patterns/caching/beta.md'], reference: ['docs/reference/guide.md'] }));
    expectFail(await sb.run(spec, ['--check']), 'STALE');
    await sb.run(spec);
    expect(sb.read(MAP)).toContain('[Alpha](patterns/caching/alpha.md) · [Alpha](patterns/caching/beta.md)');
  });

  it('a missing map, or one that lost a marker, is a finding and is not written', async () => {
    sb.write(SRC, structureJson({ caching: ['docs/patterns/caching/alpha.md'] }));
    expectFail(await sb.run(spec), `FAIL ${MAP}: is missing`);
    expect(sb.exists(MAP)).toBe(false);

    sb.write(MAP, MAP_PAGE.replace('<!-- docs-map:end -->\n', ''));
    const r = await sb.run(spec);
    expectFail(r, `FAIL ${MAP}: lacks the <!-- docs-map:end --> marker`);
    expect(sb.read(MAP)).toBe(MAP_PAGE.replace('<!-- docs-map:end -->\n', ''));
  });

  it('a missing, unreadable or listless structure file is a finding on it', async () => {
    sb.write(MAP, MAP_PAGE);
    expectFail(await sb.run(spec, ['--check']), `FAIL ${SRC}: is missing`);
    sb.write(SRC, '{ oops');
    expectFail(await sb.run(spec, ['--check']), `FAIL ${SRC}: is not valid JSON`);
    sb.write(SRC, '{"version": 1}\n');
    expectFail(await sb.run(spec, ['--check']), `FAIL ${SRC}: has no areas list`);
    expect(sb.read(MAP)).toBe(MAP_PAGE);
  });

  it('skips an area with no id', async () => {
    sb.write(MAP, MAP_PAGE);
    sb.write(SRC, JSON.stringify({ version: 1, updated: '2026-09-24', note: 'x', areas: [{ label: 'No id', pages: [{ label: 'X', source: 'docs/x.md' }] }] }));
    expectPass(await sb.run(spec));
    expect(sb.read(MAP)).not.toContain('docs/x.md');
  });

  it('exits 2 on an unknown flag and writes nothing', async () => {
    tree();
    const before = sb.snapshot();
    const r = await sb.run(spec, ['--nope']);
    expectMisuse(r);
    expect(r.out).toBe('');
    expect(sb.snapshot()).toEqual(before);
  });
});

it('holds the real map: its block is fresh against the real structure file', async () => {
  const r = await capture(spec, ['--check'], REPO_ROOT);
  expectPass(r);
  expect(r.out).toBe(`[map-fresh] ${MAP} is in sync with ${SRC}`);
});

/**
 * gen-tours, the tour- and fluency-block generator. The same marked-block contract as gen-relations, over the
 * learning-path file: the theme page gets its tour, each staged page its
 * fluency item, a page holding a marker but staged nowhere an empty block,
 * and nothing is drawn from a profile the renderers cannot draw. The real
 * tree comes last, in sync byte for byte with what the converter wrote.
 */

import fs from 'node:fs';
import path from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { markers } from '../lib/generated.js';
import { capture, expectFail, expectMisuse, expectPass, makeSandbox, REPO_ROOT, type Sandbox } from '../lib/sandbox.js';
import { STRUCTURE } from '../lib/page-refs.js';
import { HEADER, json, learningPageText, learningPathsJson, NOTES, PROFILES, rowOf, sourceTree } from '../lib/fixtures.js';
import { FIX } from './blocks.js';
import { LEARNING_PATHS, spec } from './gen-tours.js';

let sb: Sandbox;
beforeEach(() => {
  sb = makeSandbox();
});
afterEach(() => sb.cleanup());

const block = (name: string): string => {
  const [open, close] = markers(name);
  return [`## ${name}`, `<!--meta block=${name}-->`, '', open, 'a stale line', close].join('\n');
};
const inside = (text: string, name: string): string => {
  const [open, close] = markers(name);
  return text.slice(text.indexOf(open) + open.length, text.indexOf(close));
};
const STAMP = `<!-- GENERATED by gen-tours from ${LEARNING_PATHS}. Do not edit this block. -->`;
const findings = (err: string): string[] => err.split('\n').filter((l) => l.startsWith('[tours-fresh] FAIL'));

/** The theme 'starting' tours alpha then beta; gamma holds a fluency block but is on no tour. */
function tree(profiles: readonly unknown[] = PROFILES, notes: unknown = NOTES): void {
  sourceTree(sb);
  sb.write(LEARNING_PATHS, learningPathsJson(profiles, notes));
  sb.write(rowOf('starting').source, learningPageText('starting', 'stable', block('tour')));
  for (const slug of ['alpha', 'beta', 'gamma']) sb.write(rowOf(slug).source, learningPageText(slug, 'stable', block('fluency')));
}

describe('the blocks', () => {
  it('splices the tour into the theme and a fluency item into each member; a second run and the check change nothing', async () => {
    tree();
    let r = await sb.run(spec);
    expectPass(r);
    expect(r.out).toBe(`[tours-fresh] wrote 4 of 4 pages' tour and fluency blocks from ${LEARNING_PATHS}`);
    expect(inside(sb.read(rowOf('starting').source), 'tour')).toBe(
      [
        '',
        '',
        STAMP,
        '',
        '### [Alpha](../patterns/alpha.md) {#tour-alpha}',
        '',
        'Start here.',
        '',
        '### [Beta](../patterns/beta.md) {#tour-beta}',
        '',
        'Then this.',
        '',
        '',
      ].join('\n'),
    );
    expect(inside(sb.read(rowOf('alpha').source), 'fluency')).toBe(
      `\n\n${STAMP}\n\n- [Starting](../themes/starting.md) — Start here, briefly. {#fluency-starting}\n\n`,
    );
    expect(inside(sb.read(rowOf('gamma').source), 'fluency')).toBe(`\n\n${STAMP}\n\n`);

    const once = sb.snapshot();
    r = await sb.run(spec);
    expect(r.out).toBe(`[tours-fresh] wrote 0 of 4 pages' tour and fluency blocks from ${LEARNING_PATHS}`);
    expect(sb.snapshot()).toEqual(once);
    r = await sb.run(spec, ['--check']);
    expectPass(r);
    expect(r.out).toBe(`[tours-fresh] 4 pages' tour and fluency blocks are in sync with ${LEARNING_PATHS}`);
  });

  it('an edit inside a tour is STALE naming the theme page and the repair; a file with no notes key renders links alone', async () => {
    tree();
    await sb.run(spec);
    const theme = rowOf('starting').source;
    sb.write(theme, sb.read(theme).replace('Start here.', 'Start there.'));
    expectFail(await sb.run(spec, ['--check']), `[tours-fresh] FAIL: ${theme} is STALE — run: ${FIX}`);

    tree(PROFILES, null);
    expectPass(await sb.run(spec));
    expect(inside(sb.read(theme), 'tour')).toBe(`\n\n${STAMP}\n\n### [Alpha](../patterns/alpha.md) {#tour-alpha}\n\n### [Beta](../patterns/beta.md) {#tour-beta}\n\n`);
  });

  it('names a staged page that lost its fluency markers, and still writes the others', async () => {
    tree();
    sb.write(rowOf('beta').source, learningPageText('beta'));
    const r = await sb.run(spec);
    const [open, close] = markers('fluency');
    expect(findings(r.err)).toEqual([
      `[tours-fresh] FAIL ${rowOf('beta').source}: lacks the ${open} marker`,
      `[tours-fresh] FAIL ${rowOf('beta').source}: lacks the ${close} marker`,
    ]);
    expect(inside(sb.read(rowOf('alpha').source), 'fluency')).toContain('Start here, briefly.');
  });

  it('exits 2 on misuse, writing nothing', async () => {
    tree();
    const before = sb.snapshot();
    expectMisuse(await sb.run(spec, ['--nope']));
    expect(sb.snapshot()).toEqual(before);
  });
});

describe('a source it cannot draw from writes nothing', () => {
  it('names each missing data file', async () => {
    const r = await sb.run(spec);
    expect(findings(r.err)).toEqual(
      [LEARNING_PATHS, STRUCTURE].map((f) => `[tours-fresh] FAIL ${f}: is missing — every tour and fluency block is rendered from it`),
    );
  });

  it('names a structure without areas, a file without profiles, and notes that are not an object', async () => {
    tree();
    sb.write(STRUCTURE, json({ ...HEADER }));
    sb.write(LEARNING_PATHS, json({ ...HEADER, notes: [] }));
    const r = await sb.run(spec);
    expect(findings(r.err)).toEqual([
      `[tours-fresh] FAIL ${STRUCTURE}: has no areas list, so no page is published`,
      `[tours-fresh] FAIL ${LEARNING_PATHS}: has no profiles list`,
      `[tours-fresh] FAIL ${LEARNING_PATHS}: notes is not an object keyed by route`,
    ]);
  });

  it('names each profile the renderers cannot draw, and a tour block no profile owns', async () => {
    tree([...PROFILES, 7, { id: 'ghost', stages: [] }, { id: 'gamma', stages: ['/patterns/gone.html', 4] }]);
    sb.write(rowOf('delta').source, learningPageText('delta', 'stable', block('tour')));
    const before = sb.snapshot();
    const r = await sb.run(spec);
    const gate = 'run: make gate G=check-learning-paths';
    expect(findings(r.err)).toEqual([
      `[tours-fresh] FAIL ${LEARNING_PATHS}: profiles[1] lacks an id or a stages list — ${gate}`,
      `[tours-fresh] FAIL ${LEARNING_PATHS}: profiles[2] is named ghost, which is no published page — its tour renders on that page — ${gate}`,
      `[tours-fresh] FAIL ${LEARNING_PATHS}: profiles[3] stages "/patterns/gone.html", which is no published route — ${gate}`,
      `[tours-fresh] FAIL ${LEARNING_PATHS}: profiles[3] stages 4, which is no published route — ${gate}`,
      `[tours-fresh] FAIL ${rowOf('delta').source}: holds a tour block, but no profile in ${LEARNING_PATHS} is named delta — ${gate}`,
    ]);
    expect(sb.snapshot()).toEqual(before);
  });

  it('names a page it cannot title, and writes no page', async () => {
    tree();
    sb.write(rowOf('delta').source, '# Delta, no frontmatter\n');
    const before = sb.snapshot();
    const r = await sb.run(spec);
    expect(findings(r.err)).toEqual([`[tours-fresh] FAIL ${rowOf('delta').source}: declares no title — a generated block links a page by its title`]);
    expect(sb.snapshot()).toEqual(before);
  });
});

describe('the real tree', () => {
  it('finds every tour and fluency block the converter wrote in sync: one theme per profile, one page per stage', async () => {
    const lp = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, LEARNING_PATHS), 'utf8')) as { profiles: { id: string; stages: string[] }[] };
    const themes = new Set(lp.profiles.map((p) => p.id));
    const routes = new Set(lp.profiles.flatMap((p) => p.stages));
    const structure = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, STRUCTURE), 'utf8')) as { areas: { pages: { slug: string; route: string }[] }[] };
    const pages = structure.areas.flatMap((a) => a.pages).filter((p) => themes.has(p.slug) || routes.has(p.route)).length;
    const r = await capture(spec, ['--check'], REPO_ROOT);
    expectPass(r);
    expect(r.out).toBe(`[tours-fresh] ${pages} pages' tour and fluency blocks are in sync with ${LEARNING_PATHS}`);
  });
});

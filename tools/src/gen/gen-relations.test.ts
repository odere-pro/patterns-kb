/**
 * gen-relations, the relationships-block generator, and ./blocks.ts, which it shares with gen-tours. What is defended
 * is the marked-block contract on real pages: only the inside of a block
 * changes; an edit inside is STALE and one outside is not; a page that lost a
 * marker is a finding and the other pages are still written; nothing is drawn
 * from an edge the renderer cannot draw. The real tree comes last: its blocks
 * are what the converter wrote, so the check passes byte for byte.
 */

import fs from 'node:fs';
import path from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { markers } from '../lib/generated.js';
import { capture, expectFail, expectMisuse, expectPass, makeSandbox, REPO_ROOT, type Sandbox } from '../lib/sandbox.js';
import { STRUCTURE } from '../lib/page-refs.js';
import { EDGES, HEADER, json, learningModelJson, LEARNING_VERBS, learningPageText, rowOf, sourceTree } from '../lib/fixtures.js';
import { FIX, holdsMarker } from './blocks.js';
import { CONTENT_MODEL, RELATIONS, renderVerbs, spec } from './gen-relations.js';

let sb: Sandbox;
beforeEach(() => {
  sb = makeSandbox();
});
afterEach(() => sb.cleanup());

const [OPEN, CLOSE] = markers('relationships');
const BLOCK = ['## How it relates', '<!--meta block=relationships-->', '', OPEN, 'a stale line', CLOSE].join('\n');
const findings = (err: string): string[] => err.split('\n').filter((l) => l.startsWith('[relations-fresh] FAIL'));

/** The learning tree, with a relationships block on every page that holds an edge. */
function tree(edges: readonly unknown[] = EDGES): void {
  sourceTree(sb, edges);
  for (const slug of ['alpha', 'beta', 'gamma', 'delta']) sb.write(rowOf(slug).source, learningPageText(slug, 'stable', BLOCK));
}

/** The text between a page's markers. */
const inside = (text: string): string => text.slice(text.indexOf(OPEN) + OPEN.length, text.indexOf(CLOSE));

describe('the blocks', () => {
  it('splices each page, leaving every byte outside the markers; a second run and the check change nothing', async () => {
    tree();
    const before = sb.read(rowOf('alpha').source);
    let r = await sb.run(spec);
    expectPass(r);
    expect(r.out).toBe(`[relations-fresh] wrote 4 of 4 pages' relationships blocks from ${RELATIONS}`);
    const alpha = sb.read(rowOf('alpha').source);
    expect(alpha.slice(0, alpha.indexOf(OPEN))).toBe(before.slice(0, before.indexOf(OPEN)));
    expect(alpha.slice(alpha.indexOf(CLOSE))).toBe(before.slice(before.indexOf(CLOSE)));
    expect(inside(alpha)).toBe(
      [
        '',
        '',
        `<!-- GENERATED by gen-relations from ${RELATIONS}. Do not edit this block. -->`,
        '',
        '**Combines with**',
        '',
        '- [Gamma](./gamma.md) — Alpha with gamma.',
        '',
        '**Requires**',
        '',
        '- [Beta](./beta.md) — Read beta first.',
        '',
        '',
      ].join('\n'),
    );
    expect(inside(sb.read(rowOf('delta').source))).toContain('**Enables**\n\n- [Beta](../patterns/beta.md)\n');

    const once = sb.snapshot();
    r = await sb.run(spec);
    expect(r.out).toBe(`[relations-fresh] wrote 0 of 4 pages' relationships blocks from ${RELATIONS}`);
    expect(sb.snapshot()).toEqual(once);
    r = await sb.run(spec, ['--check']);
    expectPass(r);
    expect(r.out).toBe(`[relations-fresh] 4 pages' relationships blocks are in sync with ${RELATIONS}`);
  });

  it('an edit inside a block is STALE naming the page and the repair; an edit outside every block is not', async () => {
    tree();
    await sb.run(spec);
    const alpha = rowOf('alpha').source;
    const clean = sb.read(alpha);
    sb.write(alpha, clean.replace('Alpha with gamma.', 'Alpha with gamma, edited.'));
    let r = await sb.run(spec, ['--check']);
    expectFail(r, `[relations-fresh] FAIL: ${alpha} is STALE — run: ${FIX}`);

    sb.write(alpha, clean.replace('What alpha is, in one line.', 'What alpha is, said by hand.'));
    r = await sb.run(spec, ['--check']);
    expectPass(r);
  });

  it('names a page that holds edges but lost a marker, and still writes the others (marked-blocks-C5, C6)', async () => {
    tree();
    const beta = rowOf('beta').source;
    sb.write(beta, learningPageText('beta', 'stable', BLOCK.replace(`${CLOSE}`, '')));
    const r = await sb.run(spec);
    expectFail(r);
    expect(r.out).toBe('');
    expect(findings(r.err)).toEqual([`[relations-fresh] FAIL ${beta}: lacks the ${CLOSE} marker`]);
    expect(sb.read(beta)).toBe(learningPageText('beta', 'stable', BLOCK.replace(`${CLOSE}`, '')));
    expect(inside(sb.read(rowOf('alpha').source))).toContain('**Requires**');
  });

  it('empties the block on a page whose edges are gone, and leaves a page with neither edge nor marker alone', async () => {
    tree(EDGES.slice(0, 1));
    const gamma = rowOf('gamma').source;
    expectPass(await sb.run(spec));
    expect(inside(sb.read(gamma))).toBe(`\n\n<!-- GENERATED by gen-relations from ${RELATIONS}. Do not edit this block. -->\n\n`);
    expect(sb.read(rowOf('starting').source)).toBe(learningPageText('starting'));
    expect(holdsMarker(sb.dir, rowOf('starting').source, 'relationships')).toBe(false);
    expect(holdsMarker(sb.dir, 'docs/gone.md', 'relationships')).toBe(false);
  });

  it('exits 2 on misuse, writing nothing', async () => {
    tree();
    const before = sb.snapshot();
    expectMisuse(await sb.run(spec, ['--nope']));
    expect(sb.snapshot()).toEqual(before);
  });
});

describe('a source it cannot draw from writes nothing', () => {
  it('names each missing data file', async () => {
    const r = await sb.run(spec);
    expect(findings(r.err)).toEqual(
      [RELATIONS, CONTENT_MODEL, STRUCTURE].map((f) => `[relations-fresh] FAIL ${f}: is missing — every relationships block is rendered from it`),
    );
  });

  it('names a verb table it cannot use, a structure without areas and a file without edges', async () => {
    tree();
    sb.write(CONTENT_MODEL, json({ ...HEADER, relations: { verbs: [] } }));
    sb.write(STRUCTURE, json({ ...HEADER }));
    sb.write(RELATIONS, json({ ...HEADER }));
    const r = await sb.run(spec);
    expect(findings(r.err)).toEqual([
      `[relations-fresh] FAIL ${CONTENT_MODEL}: has no relations.verbs list`,
      `[relations-fresh] FAIL ${STRUCTURE}: has no areas list, so no page is published`,
      `[relations-fresh] FAIL ${RELATIONS}: has no relations list`,
    ]);
  });

  it('names each edge the renderer cannot draw, pointing at the relations gate', async () => {
    tree([
      ...EDGES,
      { a: 'alpha', verb: 'combines-with', b: 'beta', note_a: 'x' },
      { a: 'alpha', verb: 'rhymes-with', b: 'beta', note_a: '', note_b: '' },
      { a: 'alpha', verb: 'combines-with', b: 'ghost', note_a: '', note_b: '' },
      null,
    ]);
    const before = sb.snapshot();
    const r = await sb.run(spec);
    const gate = 'run: make gate G=check-relations';
    expect(findings(r.err)).toEqual([
      `[relations-fresh] FAIL ${RELATIONS}: relations[4] lacks an end, its verb or a note — ${gate}`,
      `[relations-fresh] FAIL ${RELATIONS}: relations[5] "rhymes-with" is no verb in ${CONTENT_MODEL} — ${gate}`,
      `[relations-fresh] FAIL ${RELATIONS}: relations[6] names ghost, which is no published page — ${gate}`,
      `[relations-fresh] FAIL ${RELATIONS}: relations[7] lacks an end, its verb or a note — ${gate}`,
    ]);
    expect(sb.snapshot()).toEqual(before);
  });

  it('names a page it cannot title, and writes no page', async () => {
    tree();
    sb.rm(rowOf('starting').source);
    const before = sb.snapshot();
    const r = await sb.run(spec);
    expect(findings(r.err)).toEqual([`[relations-fresh] FAIL ${rowOf('starting').source}: is missing — ${STRUCTURE} publishes it at /themes/starting.html`]);
    expect(sb.snapshot()).toEqual(before);
  });
});

describe('renderVerbs', () => {
  it('reads each verb with its inverse, symmetric when it is its own, and the group order as labels', () => {
    const got = renderVerbs(JSON.parse(learningModelJson()) as unknown);
    expect(got).toMatchObject({
      verbs: { 'combines-with': { label: 'Combines with', inverse: 'combines-with', symmetric: true }, prerequisite: { label: 'Requires', symmetric: false } },
    });
    expect((got as { relOrder: string[] }).relOrder).toEqual(LEARNING_VERBS.map((v) => v.label));
  });

  it('says why when the verbs, the order or an order entry cannot be used', () => {
    expect(renderVerbs({})).toBe('has no relations.verbs list');
    expect(renderVerbs({ relations: { verbs: LEARNING_VERBS } })).toBe('has no relations.order list — the groups on a page follow it');
    expect(renderVerbs({ relations: { verbs: LEARNING_VERBS, order: ['combines-with', 'gone'] } })).toBe(
      'relations.order names "gone", which is no verb in relations.verbs',
    );
    expect(renderVerbs({ relations: { verbs: LEARNING_VERBS, order: [3] } })).toBe('relations.order names 3, which is no verb in relations.verbs');
  });
});

describe('the real tree', () => {
  it('finds every relationships block the converter wrote in sync, one page for each page an edge names', async () => {
    const rel = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, RELATIONS), 'utf8')) as { relations: { a: string; b: string }[] };
    const pages = new Set(rel.relations.flatMap((e) => [e.a, e.b]));
    const r = await capture(spec, ['--check'], REPO_ROOT);
    expectPass(r);
    expect(r.out).toBe(`[relations-fresh] ${pages.size} pages' relationships blocks are in sync with ${RELATIONS}`);
  });
});

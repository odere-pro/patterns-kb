/* 2026-07-favourites-on-pages.mjs — one-shot migration: load favourites.js on content pages.
 *
 * Favourite stopped being fixed page metadata and became per-visitor state seeded from it
 * (site/assets/favourites.js). The toggle therefore has to exist on the page it applies to,
 * not only on the hub, so every content page needs the script.
 *
 * It goes immediately after progress.js — the two are siblings, both body-end trackers that
 * inject a control into the fixed cluster, and keeping them adjacent means the next reader
 * finds them together. The page markup itself is untouched: favourites.js injects both the
 * metarow button and the floating one at runtime.
 *
 * Idempotent: a page that already references favourites.js is skipped. Run once, then delete
 * or leave as the record of the change.
 *
 *   node scripts/migrations/2026-07-favourites-on-pages.mjs [--dry]
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const ROOT = process.env.KB_ROOT
  ? resolve(process.env.KB_ROOT)
  : join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SITE = join(ROOT, "site");
const dry = process.argv.includes("--dry");

function walk(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (e.name.endsWith(".html")) out.push(p);
  }
  return out;
}

/* Matches the progress.js tag and captures its indentation and relative prefix, so the new
 * tag inherits both — pages sit at four different depths under site/. */
const AFTER = /^([ \t]*)<script src="((?:\.\.\/)*assets\/)progress\.js"><\/script>[ \t]*$/m;

let changed = 0;
let skipped = 0;
const missing = [];

for (const file of walk(SITE)) {
  const html = readFileSync(file, "utf8");
  /* A KB page, identified the way favourites.js identifies one: main.doc-wrap carrying a
   * data-kb-id. That excludes the hub (generated by build-hub, which loads the script
   * itself) and vocab.html, whose doc-wrap is documentation and names no page. */
  if (!/<main class="doc-wrap"[^>]*\bdata-kb-id=/.test(html)) continue;
  if (html.includes("assets/favourites.js")) { skipped += 1; continue; }

  const m = html.match(AFTER);
  if (!m) { missing.push(file.slice(ROOT.length + 1)); continue; }

  const [line, indent, prefix] = m;
  const out = html.replace(line, `${line}\n${indent}<script src="${prefix}favourites.js"></script>`);
  if (!dry) writeFileSync(file, out);
  changed += 1;
}

console.log(`${dry ? "would add" : "added"} favourites.js to ${changed} page(s); ${skipped} already had it.`);
if (missing.length) {
  console.error(`\n${missing.length} content page(s) load no progress.js — add the tag by hand:`);
  for (const f of missing) console.error(`  ${f}`);
  process.exit(1);
}
